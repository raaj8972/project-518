import { useEffect, useRef } from 'react';

const TARGETS = 'button, a[href], [role="button"], [role="tab"], [data-spider-web]';

function findTarget(node: EventTarget | null): HTMLElement | null {
  if (!(node instanceof Element)) return null;
  if (node.closest('[data-spider-web="off"]')) return null;
  const element = node.closest<HTMLElement>(TARGETS);
  return element && !element.matches(':disabled, [aria-disabled="true"]')
    && !element.closest('[inert], [aria-hidden="true"]') ? element : null;
}

function WebCorner({ className }: { className: string }) {
  return <svg className={className} viewBox="0 0 72 72" fill="none">
    <path d="M0 0H72M0 0L69 23M0 0L52 52M0 0L23 69M0 0V72M18 0Q16 7 17 6Q15 12 13 13Q7 15 6 17Q4 17 0 18M36 0Q31 13 34 12Q28 23 26 26Q13 28 12 34Q6 34 0 36M54 0Q48 17 51 17Q44 35 39 39Q20 44 17 51Q9 51 0 54M72 0Q64 21 68 23Q59 47 52 52Q27 59 23 68Q11 68 0 72" />
  </svg>;
}

/** One decorative frame serves mouse, keyboard and touch without intercepting input. */
export function SpiderWebHighlight() {
  const frameRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    const frame = frameRef.current;
    if (!frame) return;
    let active: HTMLElement | null = null;
    let timer: ReturnType<typeof setTimeout> | undefined;
    let touch: { id: number; x: number; y: number; moved: boolean } | null = null;
    let touching = false;

    const clearTimer = () => { clearTimeout(timer); timer = undefined; };
    const hide = () => {
      clearTimer();
      active = null;
      frame.dataset.visible = 'false';
    };
    const show = (target: HTMLElement | null) => {
      clearTimer();
      if (!target?.isConnected) { hide(); return; }
      const rect = target.getBoundingClientRect();
      const left = Math.max(0, rect.left);
      const top = Math.max(0, rect.top);
      const width = Math.min(innerWidth, rect.right) - left;
      const height = Math.min(innerHeight, rect.bottom) - top;
      if (width < 8 || height < 8) { hide(); return; }
      active = target;
      frame.style.transform = `translate3d(${left}px, ${top}px, 0)`;
      frame.style.width = `${width}px`;
      frame.style.height = `${height}px`;
      frame.style.borderRadius = getComputedStyle(target).borderRadius;
      frame.style.setProperty('--web-corner-size', `${Math.min(78, width * .42, height * .85)}px`);
      frame.dataset.visible = 'true';
    };
    const hover = (event: PointerEvent) => {
      if (event.pointerType === 'touch' || touching) return;
      const target = findTarget(event.target);
      if (target !== active) show(target);
    };
    const leave = (event: PointerEvent) => {
      if (event.pointerType === 'touch' || touching) return;
      const target = findTarget(event.relatedTarget);
      if (target !== active) show(target);
    };
    const focus = (event: FocusEvent) => {
      if (!touching) show(findTarget(event.target));
    };
    const blur = (event: FocusEvent) => {
      if (!touching) show(findTarget(event.relatedTarget));
    };
    const press = (event: PointerEvent) => {
      if (event.pointerType !== 'touch' && event.pointerType !== 'pen') return;
      touching = true;
      touch = { id: event.pointerId, x: event.clientX, y: event.clientY, moved: false };
      show(findTarget(event.target));
    };
    const move = (event: PointerEvent) => {
      if (touch?.id === event.pointerId && Math.hypot(event.clientX - touch.x, event.clientY - touch.y) > 12) {
        touch.moved = true;
        hide();
      }
    };
    const release = (event: PointerEvent) => {
      if (touch?.id !== event.pointerId) return;
      if (touch.moved || event.type === 'pointercancel') hide();
      else timer = setTimeout(hide, 1100);
      touch = null;
      // Ignore compatibility mouse/focus events generated by this tap.
      touching = true;
    };
    const mouseMove = (event: PointerEvent) => {
      if (event.pointerType === 'mouse') touching = false;
      move(event);
    };
    const keyboard = () => { touching = false; };
    const visibility = () => { if (document.hidden) hide(); };

    document.addEventListener('pointerover', hover, { passive: true });
    document.addEventListener('pointerout', leave, { passive: true });
    document.addEventListener('pointerdown', press, { passive: true });
    document.addEventListener('pointermove', mouseMove, { passive: true });
    document.addEventListener('pointerup', release, { passive: true });
    document.addEventListener('pointercancel', release, { passive: true });
    document.addEventListener('focusin', focus);
    document.addEventListener('focusout', blur);
    document.addEventListener('keydown', keyboard);
    document.addEventListener('visibilitychange', visibility);
    document.addEventListener('scroll', hide, { capture: true, passive: true });
    window.addEventListener('resize', hide, { passive: true });
    window.addEventListener('blur', hide);
    return () => {
      hide();
      document.removeEventListener('pointerover', hover);
      document.removeEventListener('pointerout', leave);
      document.removeEventListener('pointerdown', press);
      document.removeEventListener('pointermove', mouseMove);
      document.removeEventListener('pointerup', release);
      document.removeEventListener('pointercancel', release);
      document.removeEventListener('focusin', focus);
      document.removeEventListener('focusout', blur);
      document.removeEventListener('keydown', keyboard);
      document.removeEventListener('visibilitychange', visibility);
      document.removeEventListener('scroll', hide, true);
      window.removeEventListener('resize', hide);
      window.removeEventListener('blur', hide);
    };
  }, []);

  return <div ref={frameRef} className="spider-web-highlight" data-spider-web-highlight data-visible="false" aria-hidden="true">
    <WebCorner className="spider-web-highlight-corner" />
    <WebCorner className="spider-web-highlight-corner spider-web-highlight-opposite" />
  </div>;
}
