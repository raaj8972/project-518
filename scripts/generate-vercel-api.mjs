import { readdir, writeFile } from 'node:fs/promises';
const files = (await readdir(new URL('../netlify/functions/', import.meta.url))).filter(f => /\.(ts|mts)$/.test(f)).sort();
const registry = files.map(f => `  '${f.replace(/\.(ts|mts)$/, '')}': () => import('../netlify/functions/${f}'),`).join('\n');
await writeFile(new URL('../api/[...path].ts', import.meta.url), `// Generated by scripts/generate-vercel-api.mjs from the shared Netlify handlers.
import type { VercelRequest, VercelResponse } from '@vercel/node';
import { invokeHandler } from '../netlify/functions/lib/invoke-handler';
const handlers: Record<string, () => Promise<any>> = {
${registry}
};
export default async function handler(req: VercelRequest, res: VercelResponse) {
  res.setHeader('Content-Type', 'application/json');
  try {
    const pathname = new URL(req.url || '/', 'http://localhost').pathname;
    const name = pathname.replace(/^\\/(?:api|\\.netlify\\/functions)\\//, '');
    const load = Object.prototype.hasOwnProperty.call(handlers, name) ? handlers[name] : null;
    if (!load) return res.status(404).json({ error: 'API endpoint not found' });
    const module = await load();
    const headers = Object.fromEntries(Object.entries(req.headers).map(([key,value]) => [key, Array.isArray(value) ? value.join(',') : value]));
    const query = Object.fromEntries(Object.entries(req.query).filter(([key]) => key !== 'path').map(([key,value]) => [key, Array.isArray(value) ? value[0] : value]));
    const response = await invokeHandler(module, { httpMethod: req.method, headers, path: pathname,
      rawUrl: new URL(req.url || '/', String(req.headers['x-forwarded-proto'] || 'https') + '://' + String(req.headers.host || 'localhost')).href, queryStringParameters: query, multiValueQueryStringParameters: {},
      body: typeof req.body === 'string' ? req.body : JSON.stringify(req.body || {}), isBase64Encoded: false }, {});
    for (const [key,value] of Object.entries(response.headers || {})) res.setHeader(key, String(value));
    res.status(response.statusCode).send(response.isBase64Encoded ? Buffer.from(response.body || '', 'base64') : response.body || '');
  } catch {
    res.status(500).json({ error: 'API unavailable. Check server configuration.' });
  }
}
`);
console.log(`Prepared Vercel adapter for ${files.length} shared handlers`);
