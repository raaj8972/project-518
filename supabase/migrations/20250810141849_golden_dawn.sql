/*
  # Create band members table for Home Bound band management

  1. New Tables
    - `band_members`
      - `id` (bigint, primary key)
      - `name` (text, required)
      - `role` (text, required) 
      - `image` (text, required)
      - `description` (text, required)
      - `specialty` (text, required)
      - `achievements` (text array)
      - `order_position` (integer, default 1)
      - `enabled` (boolean, default true)
      - `is_featured` (boolean, default false)
      - `social_links` (jsonb)
      - `created_at` (timestamp)
      - `updated_at` (timestamp)

  2. Security
    - Enable RLS on `band_members` table
    - Add policies for public read access
    - Add policies for authenticated user management
*/

CREATE TABLE IF NOT EXISTS band_members (
  id bigint PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name text NOT NULL,
  role text NOT NULL,
  image text NOT NULL,
  description text NOT NULL,
  specialty text NOT NULL,
  achievements text[] DEFAULT '{}',
  order_position integer DEFAULT 1,
  enabled boolean DEFAULT true,
  is_featured boolean DEFAULT false,
  social_links jsonb DEFAULT '{}',
  created_at timestamptz DEFAULT now(),
  updated_at timestamptz DEFAULT now()
);

ALTER TABLE band_members ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Enable read access for all users"
  ON band_members
  FOR SELECT
  TO public
  USING (true);

CREATE POLICY "Enable insert for authenticated users"
  ON band_members
  FOR INSERT
  TO authenticated
  WITH CHECK (true);

CREATE POLICY "Enable update for authenticated users"
  ON band_members
  FOR UPDATE
  TO authenticated
  USING (true)
  WITH CHECK (true);

CREATE POLICY "Enable delete for authenticated users"
  ON band_members
  FOR DELETE
  TO authenticated
  USING (true);